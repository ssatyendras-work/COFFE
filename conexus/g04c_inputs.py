# Co-Nexus: COFFE2 inputs for X-PACE G0.4c, one per tile of P1's 60-tile grid (xmorph p1-g05 at 685ac9a), at the
# archived flut0 run's process and circuit settings (22 nm PTM bulk, pass transistors) with P1's shared routing.
#
#   python conexus/g04c_inputs.py [--export <xmorph vpr-export of p1-g05>] [--out conexus/inputs/g04c]
#
# Per tile: K, N, cluster inputs I by P1's rule (F0: Betz-Rose ceil_even(K(N+1)/2); F1: ceil_even(2K/3 N); checked
# against the export's records when --export is given), fracturable LUTs for F1, carry chain for C1/C2 (FAs per
# BLE = 1 or 2, flut0's carry type). Routing as the grid: W 300, L 4, Fc_in 0.15, Fc_out 0.10. Everything else is
# flut0's (conexus/inputs/flut0.yaml). Tiles COFFE2 cannot express are listed in manifest.json with why and the
# closest it can, not written.

import argparse
import json
import math
import os
import re

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
KS, NS = (4, 5, 6), (4, 6, 8, 10)
VARIANTS = ("F0-C0", "F0-C1", "F1-C0", "F1-C1", "F1-C2")
## P1's shared routing (xmorph p1-g05 base request).
ROUTING = {"W": 300, "L": 4, "Fcin": 0.15, "Fcout": 0.10}


def ceil_even(value):
    return int(2 * math.ceil(value / 2.0 - 1e-9))


def cluster_inputs(k, n, fracture):
    """ P1's rule (ADR-0014 of xmorph): F0 Betz and Rose, F1 two-thirds of the LUT inputs. """

    return ceil_even(k * (n + 1) / 2.0) if fracture == "F0" else ceil_even(2.0 * k / 3.0 * n)


def expressible(k, fracture, carry):
    """ None when COFFE2 can size the tile, else (why, closest COFFE2 can). """

    if fracture == "F0" and carry != "C0":
        return ("COFFE2 builds carry chains only with fracturable LUTs (utils.check_arch_params: carry chains are not compatible "
                "with non-fracturable LUTs)",
                "F0-C0 of the same K and N for the logic, and the carry chain of F1-%s at the same K and N (K5, K6) for the adder; "
                "or extend the fork with a carry chain on non-fracturable LUTs" % carry)
    # K4-F1: two 3-LUT halves, built by the fork's 3-LUT generator (coffe/lut3.py, bb8af93)
    return None


def tile_name(k, n, variant):
    return "k%d-N%d-%s" % (k, n, variant)


def write_inputs(out, export=None):
    """ The inputs and manifest.json; returns the manifest. """

    with open(os.path.join(HERE, "inputs", "flut0.yaml")) as handle:
        base = yaml.safe_load(handle)["fpga_arch_params"]
    os.makedirs(out, exist_ok=True)
    tiles, unsupported = [], []
    for k in KS:
        for n in NS:
            for variant in VARIANTS:
                fracture, carry = variant.split("-")
                name = tile_name(k, n, variant)
                i = cluster_inputs(k, n, fracture)
                if export:
                    with open(os.path.join(export, name + ".record.json")) as handle:
                        note = json.load(handle)["notes"]["cluster_inputs"]
                    if int(re.match(r"(\d+)", note).group(1)) != i:
                        raise ValueError("%s: I %d here, %s in the export" % (name, i, note))
                why = expressible(k, fracture, carry)
                if why:
                    unsupported.append({"tile": name, "why": why[0], "closest": why[1].replace("K4-N-", "k4-N%d-" % n)})
                    continue
                params = dict(base, K=k, N=n, I=i, **ROUTING)
                params["use_fluts"] = fracture == "F1"
                params["enable_carry_chain"] = 1 if carry != "C0" else 0
                params["FAs_per_flut"] = int(carry[1]) if carry != "C0" else base["FAs_per_flut"]
                header = ("# X-PACE G0.4c tile %s: flut0's process and circuit settings (22 nm PTM bulk, pass transistors), P1's routing "
                          "(W 300, L 4, Fc_in 0.15, Fc_out 0.10), I = %d by P1's rule. Generated by conexus/g04c_inputs.py; do not edit.\n" % (name, i))
                with open(os.path.join(out, name + ".yaml"), "w") as handle:
                    handle.write(header + yaml.safe_dump({"fpga_arch_params": params}, sort_keys=False))
                tiles.append({"tile": name, "K": k, "N": n, "I": i, "fracture": fracture, "carry": carry, "weight": k * n * (2 if carry != "C0" else 1)})
    tiles.sort(key=lambda t: (-t["weight"], t["tile"]))  # the largest clusters first: they take longest
    manifest = {"grid": "xmorph p1-g05 (685ac9a)", "base": "conexus/inputs/flut0.yaml", "routing": ROUTING, "order": [t["tile"] for t in tiles],
                "tiles": tiles, "unsupported": unsupported}
    with open(os.path.join(out, "manifest.json"), "w") as handle:
        json.dump(manifest, handle, indent=1)
    return manifest


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--export", default=None, help="xmorph vpr-export --grid p1-g05 output, to check I against its records")
    parser.add_argument("--out", default=os.path.join(HERE, "inputs", "g04c"))
    a = parser.parse_args()
    m = write_inputs(a.out, a.export)
    print("%d tiles written, %d COFFE2 cannot express -> %s" % (len(m["tiles"]), len(m["unsupported"]), a.out))


if __name__ == "__main__":
    main()
