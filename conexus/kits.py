    parser.add_argument("config")
    parser.add_argument("--out", required=True, help="where the kit directories go (e.g. ~/workspace/Co-Nexus/runs)")
    a = parser.parse_args()
    with open(a.config) as handle:
        config = yaml.safe_load(handle)
    payload = Payload(config["hatf_tech"])
    image = config["image"]
    archive = os.path.expanduser(image["archive"])
    for item in config["kits"]:
        kit = Kit(item, config)
        use = udocker_archive(archive, image["reference"]) if kit.engine == "udocker" else archive
        print(kit.write(os.path.join(os.path.expanduser(a.out), item["where"]), payload, use))


