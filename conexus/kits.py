def sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def udocker_archive(archive, reference):
    """ A copy of a docker save archive that udocker 1.3.x loads: index.json points straight at the amd64 manifest
    (Docker 29 writes an index of an index; ChiSER's register X-02), named; blobs unchanged. With its .sha256. """

    target = archive[:-4] + ".udocker.tar"
    if not os.path.isfile(target):
        partial = target + ".partial"
        with tarfile.open(archive) as source, tarfile.open(partial, "w") as copy:
            outer = json.load(source.extractfile("index.json"))
            inner = outer["manifests"][0]
            if inner["mediaType"].endswith("image.index.v1+json"):
                nested = json.load(source.extractfile("blobs/sha256/" + inner["digest"].split(":")[1]))
                inner = next(m for m in nested["manifests"] if m.get("platform", {}).get("architecture") == "amd64")
            entry = dict(inner, annotations={"org.opencontainers.image.ref.name": reference})
            index = json.dumps({"schemaVersion": 2, "mediaType": outer["mediaType"], "manifests": [entry]}).encode()
            for member in source.getmembers():
                if member.name == "manifest.json":
                    continue
                if member.name == "index.json":
                    member.size = len(index)
                    copy.addfile(member, io.BytesIO(index))
                else:
                    copy.addfile(member, source.extractfile(member) if member.isfile() else None)
        os.rename(partial, target)
    if not os.path.isfile(target + ".sha256"):
        with open(target + ".sha256", "w") as handle:
            handle.write("%s  %s\n" % (sha256(target), os.path.basename(target)))
    return target


class Payload(object):
    """ The code a kit runs: this branch (COFFE plus the ngspice port and conexus/) and hatf-tech's src/, at commits. """

    def __init__(self, hatf_tech):

        self.coffe_commit = self._git(COFFE, "rev-parse", "HEAD")
        self.hatf_tech = os.path.expanduser(hatf_tech)
        self.hatf_commit = self._git(self.hatf_tech, "rev-parse", "HEAD")
        if self._git(COFFE, "status", "--porcelain", "--", "coffe", "coffe.py", "conexus", "spice_models"):
            raise RuntimeError("commit the COFFE branch first: a kit runs a commit, not a working tree")
        return


    @staticmethod
    def _git(repo, *args):
        return subprocess.run(["git", "-C", repo] + list(args), capture_output=True, text=True, check=True).stdout.strip()


    def write(self, directory):
        """ payload/coffe-<commit>.tar.gz and payload/hatf-src-<commit>.tar.gz; returns their names. """

        os.makedirs(directory, exist_ok=True)
        coffe = "coffe-%s.tar.gz" % self.coffe_commit[:7]
        hatf = "hatf-src-%s.tar.gz" % self.hatf_commit[:7]
        subprocess.run("git -C %s archive --format=tar.gz --prefix=coffe/ %s > %s" % (COFFE, self.coffe_commit, os.path.join(directory, coffe)), shell=True, check=True)
        subprocess.run("git -C %s archive --format=tar.gz --prefix=hatf-src/ %s:src > %s" % (self.hatf_tech, self.hatf_commit, os.path.join(directory, hatf)), shell=True, check=True)
        with open(os.path.join(directory, "SHA256SUMS"), "w") as handle:
            for name in (coffe, hatf):
                handle.write("%s  %s\n" % (sha256(os.path.join(directory, name)), name))
        return coffe, hatf


class Kit(object):
    """ One kit: an engine (docker on Hyperion, udocker on Slurm), the runs (simulator settings) and the tiers' sizes. """

    def __init__(self, config, defaults):

        self.config, self.defaults = config, defaults
        self.name, self.engine = config["name"], config["engine"]
        if "tiles" in config:  # one run per tile input, in the manifest's order (longest first)
            with open(os.path.join(COFFE, config["tiles"], "manifest.json")) as handle:
                manifest = json.load(handle)
            self.runs = [{"name": t, "input": "%s/%s.yaml" % (config["tiles"], t)} for t in manifest["order"]]
            self.unsupported = manifest["unsupported"]
        else:
            self.runs, self.unsupported = config["runs"], []
        if self.engine == "udocker" and any(c in config["slurm"]["container"] for c in "/. []"):
            raise ValueError("udocker container names may not hold '/', '.', spaces or brackets: " + config["slurm"]["container"])
        return


    def env(self, payload_names, archive):
        """ kit.env: what every script reads. """

        c = self.config
        lines = [
            "# Names and paths of this kit (conexus/kits.py). ROOT is the Co-Nexus root on the server.",
            "KIT_NAME='%s'" % self.name, "ENGINE='%s'" % self.engine,
            "COFFE_TGZ='%s'" % payload_names[0], "HATF_TGZ='%s'" % payload_names[1],
            "IMAGE='%s'" % self.defaults["image"]["reference"], "ARCHIVE_NAME='%s'" % os.path.basename(archive),
            "ARCHIVE_LOCAL='%s'" % archive, "RUNS='%s'" % " ".join(r["name"] for r in self.runs),
            "INPUT='%s'" % c.get("input", "conexus/inputs/flut0.yaml"), "ITERATIONS='%d'" % c.get("iterations", 4),
            "A_CPUS=\"${A_CPUS:-%d}\"" % c["tier_a"]["cpus"], "B_CPUS=\"${B_CPUS:-%d}\"" % c["tier_b"]["cpus"], "MAX_LOAD=\"${MAX_LOAD:-%g}\"" % c.get("max_load", 96),
        ]
        if "tiles" in c:
            lines += ["TMAX=\"${TMAX:-%s}\"  # maximum ngspice time step for every tile (flut0 tier B decides 5p or 20p)" % c.get("tmax", "5p"),
                      "SLOTS=\"${SLOTS:-%d}\"  # tiles at once" % c["slots"], "SMOKE_TILE='%s'" % c["smoke_tile"]]
        for run in self.runs:
            lines.append("TMAX_%s=\"${TMAX:-%s}\"" % (run["name"].replace("-", "_"), run.get("tmax", "5p")) if "tiles" in c else "TMAX_%s='%s'" % (run["name"].replace("-", "_"), run.get("tmax", "5p")))
            if "input" in run:
                lines.append("INPUT_%s='%s'" % (run["name"].replace("-", "_"), run["input"]))
        if self.engine == "docker":
            lines += ["REMOTE=\"${REMOTE:-%s}\"" % c["remote"], "ROOT=\"${ROOT:-%s}\"" % c["root"]]
        else:
            s = c["slurm"]
            lines += [
                "# SLURM_LOGIN (user@host of the login node) is set by the owner: SLURM_LOGIN=user@host bash 02_push.sh",
                "SLURM_LOGIN=\"${SLURM_LOGIN:-}\"", "ROOT_TEMPLATE='%s'  # expanded on the cluster" % s["root"], "ROOT=\"${ROOT:-%s}\"" % s["root"],
                "UDOCKER_DIR=\"${UDOCKER_DIR:-$ROOT/udocker}\"", "CONTAINER='%s'" % s["container"], "EXECMODE='%s'" % s.get("execmode", "R1"),
                "PARTITION='%s'" % s["partition"], "EXCLUDE='%s'" % s.get("exclude", ""), "UDOCKER_MODULE='%s'" % s.get("module", "udocker"),
                "A_MEM='%s'" % c["tier_a"]["mem"], "A_TIME='%s'" % c["tier_a"]["time"], "B_MEM='%s'" % c["tier_b"]["mem"], "B_TIME='%s'" % c["tier_b"]["time"],
            ]
        lines += ["KITDIR=\"$ROOT/kits/$KIT_NAME\"", "SRC=\"$KITDIR/src\"", "RESULTS=\"$ROOT/runs/coffe/$KIT_NAME\""]
        return "\n".join(lines) + "\n"


    def write(self, out, payload, archive):
        """ Write the kit directory; returns it. """

        kit = os.path.join(out, self.name)
        shutil.rmtree(os.path.join(kit, "payload"), ignore_errors=True)
        os.makedirs(os.path.join(kit, "tools"), exist_ok=True)
        names = payload.write(os.path.join(kit, "payload"))
        shutil.copyfile(os.path.join(HERE, "compare.py"), os.path.join(kit, "tools", "compare.py"))
        shutil.copyfile(os.path.join(COFFE, ARCHIVE_REPORT), os.path.join(kit, "tools", "flut_report.archive.txt"))
        with open(os.path.join(kit, "kit.env"), "w") as handle:
            handle.write(self.env(names, archive))
        if "tiles" in self.config:
            scripts = TileQueueScripts(self).scripts()
            with open(os.path.join(kit, "unsupported.json"), "w") as handle:
                json.dump(self.unsupported, handle, indent=1)
        else:
            scripts = DockerScripts(self).scripts() if self.engine == "docker" else UdockerScripts(self).scripts()
        for name, text in scripts.items():
            path = os.path.join(kit, name)
            with open(path, "w") as handle:
                handle.write(text)
            if name.endswith(".sh") or name.endswith(".sbatch"):
                os.chmod(path, 0o755)
        facts = {"kit": self.name, "engine": self.engine, "coffe_commit": payload.coffe_commit, "hatf_tech_commit": payload.hatf_commit,
                 "image": self.defaults["image"]["reference"], "archive": archive, "archive_sha256": open(archive + ".sha256").read().split()[0],
                 "runs": self.runs, "tier_a": self.config["tier_a"], "tier_b": self.config["tier_b"]}
        with open(os.path.join(kit, "kit.json"), "w") as handle:
            json.dump(facts, handle, indent=1)
        with open(os.path.join(kit, "00_README.md"), "w") as handle:
            handle.write(Readme(self, facts).text())
        return kit


