def container_env(prefix):
    """ The container environment of one run, as engine options (prefix: '-e ' for docker, '--env=' for udocker). """

    pairs = [
        ("COFFE_SIMULATOR", "ngspice"), ("COFFE_NGSPICE_OSDI", ""), ("COFFE_NGSPICE_WORKERS", "$WORKERS"), ("COFFE_NGSPICE_TMAX", "$TMAX"),
        ("COFFE_NGSPICE_POINTS", "$OUT/points"), ("CONEXUS_HOST", "$(hostname)"), ("HOME", "/tmp"),
        ("PYTHONPATH", "$SRC/coffe:$SRC/hatf-src:/opt/conexus/py/lib/python3.12/site-packages"),
    ]
    return " ".join('%s"%s=%s"' % (prefix, k, v) for k, v in pairs)


